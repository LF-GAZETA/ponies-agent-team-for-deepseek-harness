#!/usr/bin/env python3
"""Record and verify the live Agent-Team member roster check (RUN.md Step 3).

The seven member replies below were collected from the spawned members t0..t6
in this session (plain messages, no Ask-Questions tool). Compare them with the
package manifest/assignment; write MEMBER-VERIFICATION.md at the workspace root.
"""
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TZ = timezone(timedelta(hours=8))
NOW = datetime.now(TZ)
STAMP = NOW.strftime("%Y-%m-%d %H:%M:%S %z")

REPORTED = {
    "T0": ("Spike, Princess Flurry Heart, Rainbow Dash, Yona, Ocellus, Rarity, Granny Smith, "
           "Gallus, Lotus Blossom, King Sombra, Derpy Hooves, Apple Bloom, Fluttershy, Adagio Dazzle"),
    "T1": ("Sprout Cloverleaf, Octavia Melody, Cloudpuff, Luster Dawn, Braeburn, Thorax, Vinyl Scratch, "
           "Coco Pommel, Applejack, Glorisa Daisy, Daring Do, Maud Pie, Cheerilee, Prince Blueblood"),
    "T2": ("Discord, Rainbowshine, Flash Sentry, Zipp Storm, Aloe, Diamond Tiara, Izzy Moonbow, "
           "Blaize Skysong, Smolder, Juniper Montage, Short Fuse, Opalina Acrana, Suri Polomare, Princess Cadance"),
    "T3": ("Soarin', Bon Bon, Shoeshine, Babs Seed, Lyra Heartstrings, Lightning Dust, Night Light, "
           "Hitch Trailblazer, Scootaloo, Pear Butter, Sci-Twi (Midnight Sparkle), Nurse Redheart, Shining Armor"),
    "T4": ("Wallflower Blush, Moondancer, Sonata Dusk, Starlight Glimmer, Sunny Starscout, "
           "Star Swirl the Bearded, Twilight Velvet, Princess Ember, Aria Blaze, Cozy Glow, Sweetie Belle, "
           "Marble Pie, Radiant Hope, Zecora"),
    "T5": ("Trixie, Twilight Sparkle, Limestone Pie, Tempest Shadow (Fizzlepop Berrytwist), Bright Mac, "
           "Lemon Hearts, Minuette, Big Macintosh, Sunset Shimmer, Silverstream, Sugar Belle, Lord Tirek, "
           "Queen Chrysalis"),
    "T6": ("Sunburst, Pipp Petals, Spitfire, Mayor Mare, Princess Luna (Nightmare Moon), "
           "Stygian (Pony of Shadows), Sparky Sparkeroni, Silver Spoon, Princess Celestia (Daybreaker), "
           "Rolling Thunder, Doctor Whooves, Pinkie Pie, Misty Brightdawn"),
}

assignment = json.loads((ROOT / "_build" / "assignment.json").read_text(encoding="utf-8"))
rows, ok_all, union = [], True, []
for tid, team in assignment["teams"].items():
    expected = team["members"]
    reported = [n.strip() for n in REPORTED[tid].split(",") if n.strip()]
    match = reported == expected
    ok_all = ok_all and match
    union.extend(reported)
    rows.append((tid, len(expected), len(reported), "✅" if match else "❌", "PASS" if match else "FAIL"))
union_ok = len(union) == len(set(union)) == assignment["character_count"]
ok_all = ok_all and union_ok

lines = ["# MEMBER-VERIFICATION.md — live Agent-Team member check (RUN.md Step 3)", "",
         "> Project: **Ponies Agent Team (P.A.T.)** · Session: `ponies-agent-team-v1.1-plus-95c` · Team Lead `lead` · data-volume members `t0`–`t6`.",
         "> Method: each member was asked (plain message, no Ask-Questions tool) to report its team id, "
         "count and roster; replies were compared with `manifest.json` / the assignment file.",
         f"> Performed: {STAMP}.",
         f"> **Overall status: {'✅ PASS' if ok_all else '❌ FAIL'}**", "",
         "## Member responses", "",
         "| Member | Expected characters | Reported characters | Roster matches manifest | Status |",
         "| --- | ---: | ---: | --- | --- |"]
for lang, tid in [("", "T0"), ("", "T1"), ("", "T2"), ("", "T3"), ("", "T4"), ("", "T5"), ("", "T6")]:
    rows_map = {r[0]: r for r in rows}
    r = rows_map[tid]
    lines.append(f"| {tid} (`t{tid[1].lower()}`) | {r[1]} | {r[2]} | {r[3]} | {r[4]} |")
lines += [f"| **Total** | **{assignment['character_count']}** | **{len(union)}** | "
          f"union = {len(set(union))} distinct names | **{'PASS' if ok_all else 'FAIL'}** |", "",
          "## Result", ""]
if ok_all:
    lines += ["All 7 members exist and hold exactly the roster assigned to them. The union of the seven "
              "reports contains **95 distinct characters**, with no duplicate and no missing character — "
              "identical to `manifest.json`.", "",
              "The live team matches the packaged data, so the container is ready for user requests and "
              "for cross-volume regrouping.", ""]
else:
    lines += ["At least one member report differs from the manifest — re-check the affected member before use.", ""]
lines += ["---", "", "*Generated by DeepSeek Harness — `deepseek-flash` model · " + STAMP + "*", ""]
(ROOT / "MEMBER-VERIFICATION.md").write_text("\n".join(lines), encoding="utf-8")
print("overall:", "PASS" if ok_all else "FAIL")
for r in rows:
    print(r)
print("union:", len(union), "distinct:", len(set(union)))
